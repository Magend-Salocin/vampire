// ─── SPRITE DRAWING ENGINE ─────────────────────────────────
// All sprites drawn procedurally from pixel arrays (MO5 style)
// Each sprite = [width, height, [row of colors...]]

function drawSprite(ctx, sprite, x, y, flipX=false, tint=null) {
  const {w, h, pixels} = sprite;
  const pw = 1;
  for (let row=0; row<h; row++) {
    for (let col=0; col<w; col++) {
      let c = pixels[row][col];
      if (!c || c==='_') continue;
      if (tint) c = tint;
      ctx.fillStyle = c;
      const dx = flipX ? x + (w-1-col)*pw : x + col*pw;
      ctx.fillRect(dx, y + row*pw, pw, pw);
    }
  }
}

